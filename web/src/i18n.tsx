const DICTS: Record<Locale, Dict> = { en, zh, ja };

export const LOCALE_LABELS: Record<Locale, string> = { en: 'English', zh: '中文', ja: '日本語' };

const STORAGE_KEY = 'weblift.locale';

function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  // A query override makes a shared link reproducible and lets QA check a locale
  // without touching browser settings.
  const fromQuery = new URLSearchParams(window.location.search).get('lang');
  if (fromQuery && fromQuery in DICTS) return fromQuery as Locale;
  const stored = window.localStorage.getItem(STORAGE_KEY) as Locale | null;
  if (stored && stored in DICTS) return stored;
  const nav = window.navigator.language.toLowerCase();
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('zh')) return 'zh';
  return 'en';
}

export interface LocalizableFinding {
  message: string;
  messageKey?: string;
  messageParams?: Record<string, string | number>;
}

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
  /** Localized one-line finding summary, falling back to the analyzer's English text. */
  findingMessage: (finding: LocalizableFinding) => string;
  severity: (value: Severity) => string;
  level: (value: MigrationLevel) => string;
  status: (value: FindingStatus) => string;
  category: (value: Category) => string;
  phase: (value: ScanPhase) => string;
  scanStatus: (value: ScanStatus) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);

  useEffect(() => {
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : locale === 'ja' ? 'ja-JP' : 'en';
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  const value = useMemo<I18nValue>(() => {
    const dict = DICTS[locale];
    const t = (key: TranslationKey, vars?: Record<string, string | number>): string => {
      const template = dict[key] ?? en[key] ?? key;
      if (!vars) return template;
      return Object.entries(vars).reduce((acc, [name, replacement]) => acc.replace(`{${name}}`, String(replacement)), template);
    };
    return {
      locale,
      setLocale,
      t,
      findingMessage: (finding: LocalizableFinding) => localizedMessage(locale, finding),
      severity: (v) => t(`severity.${v}` as TranslationKey),
      level: (v) => t(`level.${v}` as TranslationKey),
      status: (v) => t(`status.${v}` as TranslationKey),
      category: (v) => t(`category.${v}` as TranslationKey),
      phase: (v) => t(`phase.${v}` as TranslationKey),
      scanStatus: (v) => t(`scanStatus.${v}` as TranslationKey),
    };
  }, [locale, setLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
