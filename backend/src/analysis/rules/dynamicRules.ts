import { rawAttributeValue } from '../../parser/htmlParser.js';
import { describeRegion, intersectsRegions } from '../../parser/jspAnalyzer.js';
import { memberPath, walkJs, type JsNode } from '../../parser/jsParser.js';
import type { FileContext, RawFinding, Rule, RuleDraft } from '../types.js';
import { makeFinding } from '../finding.js';

const ruleList: RuleDraft[] = [];

function define(draft: RuleDraft): void {
  ruleList.push(draft);
}

function asRule(draft: RuleDraft): Rule {
  return draft as unknown as Rule;
}

function eachNode(ctx: FileContext, visit: (node: JsNode, unit: FileContext['parsed']['jsUnits'][number]) => void): void {
  for (const unit of ctx.parsed.jsUnits) {
    if (!unit.result.ast) continue;
    walkJs(unit.result.ast, (node) => visit(node, unit));
  }
}

define({
  meta: {
    id: 'WL-JSP-001',
    name: 'Dynamic JSP region inside analyzed block',
    version: '1.0.0',
    description:
      'Server-side code embedded in a <script> or <style> block. The static analyzer can only see the surrounding fragments.',
    language: 'jsp',
    category: 'DYNAMIC_CODE',
    defaultSeverity: 'MEDIUM',
    defaultMigrationLevel: 'MANUAL',
    basis: 'A JSP dynamic region (scriptlet, expression, EL, tag) intersecting a block that was analyzed as JavaScript or CSS.',
    tags: ['jsp', 'dynamic'],
  },
  detect(ctx) {
    if (ctx.language !== 'jsp' || ctx.dynamicRegions.length === 0) return [];
    const out: RawFinding[] = [];
    const seen = new Set<number>();
    for (const unit of [...ctx.parsed.jsUnits, ...ctx.parsed.cssUnits]) {
      if (!unit.dynamic || !unit.dynamicRegion) continue;
      const region = unit.dynamicRegion;
      if (seen.has(region.start)) continue;
      seen.add(region.start);
      out.push(
        makeFinding(asRule(this), ctx, {
          startOffset: region.start,
          endOffset: region.end,
          confidence: 'NEEDS_ANALYSIS',
          message: `Server-side code inside ${unit.container} makes this block only partially analyzable`,
          risk:
            'The generated output of this block depends on server state at request time. Anything the scan reports inside the block is based on the masked template, so a construct produced at runtime (concatenated handler names, generated event names, injected script URLs) will not be detected. Findings here cannot be auto-converted because the resulting code is unknown until runtime.',
          recommendation:
            'Extract static logic into an external .js file referenceable by the scanner, or replace inline server-side generation with a data attribute plus client-side code. Until then, review this block manually and treat its findings as advisory.',
          evidence: {
            kind: 'DynamicRegion',
            matched: describeRegion(region),
            container: unit.container,
            detail: {
              regionKind: region.kind,
              regionLength: region.end - region.start,
              touchesDynamicRegion: true,
            },
          },
        }),
      );
    }
    return out;
  },
});

define({
  meta: {
    id: 'WL-JSP-002',
    name: 'Asset URL built by server-side code',
    version: '1.0.0',
    description: 'src/href/action attributes whose value is generated by JSP expressions or EL, so the target cannot be resolved statically.',
    language: 'jsp',
    category: 'DYNAMIC_CODE',
    defaultSeverity: 'MEDIUM',
    defaultMigrationLevel: 'MANUAL',
    basis: 'An attribute among src/href/action whose raw value contains <% or ${ or #{.',
    tags: ['jsp', 'dynamic-reference'],
  },
  detect(ctx) {
    if (ctx.language !== 'jsp') return [];
    const html = ctx.parsed.html;
    if (!html) return [];
    const out: RawFinding[] = [];
    for (const element of html.elements) {
      const tag = (element.tagName ?? '').toLowerCase();
      for (const attr of element.attrs ?? []) {
        const name = attr.name.toLowerCase();
        if (!['src', 'href', 'action', 'data'].includes(name)) continue;
        const raw = rawAttributeValue(element, attr.name, ctx.text);
        if (!raw) continue;
        if (!/<%|\$\{|#\{/.test(raw.value)) continue;
        const start = raw.offset + Math.max(0, raw.value.search(/<%|\$\{|#\{/));
        out.push(
          makeFinding(asRule(this), ctx, {
            startOffset: start,
            endOffset: raw.offset + raw.value.length,
            confidence: 'NEEDS_ANALYSIS',
            message: `<${tag} ${name}> target is produced by server-side code`,
            risk:
              'The reference graph cannot resolve this link, so the file it points at is invisible to dependency analysis. If the generated URL is assembled from a variable, the same page may load different scripts per request, which means a scan can never cover all runtime paths.',
            recommendation:
              'Prefer a static path plus a base URL variable, so the reference is resolvable. If the URL must stay dynamic, document the possible targets and add them to the dependency analysis manually.',
            evidence: {
              kind: 'Attribute',
              matched: raw.value.slice(0, 120),
              detail: { tag, attribute: name, dynamic: true },
            },
          }),
        );
      }
    }
    return out;
  },
});

define({
  meta: {
    id: 'WL-DYN-001',
    name: 'Script URL assembled at runtime',
    version: '1.0.0',
    description: 'A script element src assigned from a concatenated string, a common IE-era lazy-loading pattern.',
    language: 'javascript',
    category: 'DYNAMIC_CODE',
    defaultSeverity: 'MEDIUM',
    defaultMigrationLevel: 'MANUAL',
    basis: 'AssignmentExpression whose left side is a .src member and whose right side is a binary expression or template literal with interpolation.',
    tags: ['dynamic-reference'],
  },
  detect(ctx) {
    const out: RawFinding[] = [];
    eachNode(ctx, (node, unit) => {
      if (node.type !== 'AssignmentExpression') return;
      const left = node.left as JsNode | undefined;
      const right = node.right as JsNode | undefined;
      if (!left || !right || left.type !== 'MemberExpression') return;
      const prop = left.property as JsNode | undefined;
      const propValue = !left.computed && prop?.type === 'Identifier' ? prop.name : null;
      if (propValue !== 'src') return;
      const dynamicRight =
        right.type === 'BinaryExpression' ||
        (right.type === 'TemplateLiteral' && ((right.expressions as JsNode[]) ?? []).length > 0);
      if (!dynamicRight) return;
      out.push(
        makeFinding(asRule(this), ctx, {
          startOffset: node.start ?? 0,
          endOffset: node.end ?? 0,
          confidence: 'NEEDS_ANALYSIS',
          message: 'Script/element URL is assembled by string concatenation',
          risk:
            'The target file cannot be determined statically, so the referenced script never appears in the dependency graph and is never scanned. Anything wrong inside it stays invisible until runtime.',
          recommendation:
            'Replace concatenation with a static manifest or a data attribute, so targets are enumerable. If the pattern must stay, list the possible targets in the project notes for manual review.',
          evidence: {
            kind: 'AssignmentExpression',
            matched: ctx.text.slice(node.start ?? 0, node.end ?? 0).slice(0, 200),
            container: unit.container,
            detail: { target: 'src', dynamicParts: 'concatenation' },
          },
        }),
      );
    });
    return out;
  },
});

define({
  meta: {
    id: 'WL-DYN-002',
    name: 'document.write with generated markup',
    version: '1.0.0',
    description: 'document.write / writeln called with concatenated HTML, typically injecting scripts or IE-specific markup.',
    language: 'javascript',
    category: 'DYNAMIC_CODE',
    defaultSeverity: 'MEDIUM',
    defaultMigrationLevel: 'MANUAL',
    basis: 'CallExpression on document.write or document.writeln whose first argument is a binary expression or interpolated template literal.',
    tags: ['dynamic-markup'],
  },
  detect(ctx) {
    const out: RawFinding[] = [];
    eachNode(ctx, (node, unit) => {
      if (node.type !== 'CallExpression') return;
      const callee = node.callee as JsNode | undefined;
      if (!callee || callee.type !== 'MemberExpression') return;
      const path = memberPath(callee);
      if (path !== 'document.write' && path !== 'document.writeln') return;
      const args = (node.arguments as JsNode[]) ?? [];
      const first = args[0];
      if (!first) return;
      const dynamic = first.type === 'BinaryExpression' || (first.type === 'TemplateLiteral' && ((first.expressions as JsNode[]) ?? []).length > 0);
      if (!dynamic) return;
      out.push(
        makeFinding(asRule(this), ctx, {
          startOffset: node.start ?? 0,
          endOffset: node.end ?? 0,
          confidence: 'NEEDS_ANALYSIS',
          message: `${path} generates markup at runtime`,
          risk:
            'Generated markup cannot be parsed by the scanner, so scripts or inline handlers injected here are never analyzed. In Chrome, document.write during load behaves differently from IE when the document is already closed, and injected <script> tags are fetched asynchronously by default.',
          recommendation:
            'Replace with explicit DOM construction (createElement + appendChild). If markup must be generated, keep it as a static template and fill data only, so the scanner can see it.',
          evidence: {
            kind: 'CallExpression',
            matched: ctx.text.slice(node.start ?? 0, node.end ?? 0).slice(0, 200),
            container: unit.container,
            detail: { api: path, argumentKind: first.type },
          },
        }),
      );
    });
    return out;
  },
});

define({
  meta: {
    id: 'WL-DYN-003',
    name: 'eval / Function / string timer',
    version: '1.0.0',
    description: 'Code executed from a string through eval, new Function, or setTimeout/setInterval with a string argument.',
    language: 'javascript',
    category: 'DYNAMIC_CODE',
    defaultSeverity: 'MEDIUM',
    defaultMigrationLevel: 'MANUAL',
    basis: 'CallExpression to eval, NewExpression on Function, or a timer call whose first argument is a string literal.',
    tags: ['dynamic-code', 'csp'],
  },
  detect(ctx) {
    const out: RawFinding[] = [];
    eachNode(ctx, (node, unit) => {
      let api: string | null = null;
      if (node.type === 'CallExpression') {
        const callee = node.callee as JsNode | undefined;
        if (callee?.type === 'Identifier' && callee.name === 'eval') api = 'eval';
        const path = callee ? memberPath(callee) : null;
        if (path === 'window.setTimeout' || path === 'window.setInterval' || path === '*.setTimeout' || path === '*.setInterval') {
          const first = ((node.arguments as JsNode[]) ?? [])[0];
          if (first?.type === 'StringLiteral') api = path.split('.').pop() ?? 'timer';
        }
      }
      if (node.type === 'NewExpression') {
        const callee = node.callee as JsNode | undefined;
        if (callee?.type === 'Identifier' && callee.name === 'Function') api = 'new Function';
      }
      if (!api) return;
      out.push(
        makeFinding(asRule(this), ctx, {
          startOffset: node.start ?? 0,
          endOffset: node.end ?? 0,
          confidence: 'NEEDS_ANALYSIS',
          message: `Executes code from a string via ${api}`,
          risk:
            'Code built as a string is invisible to static analysis, so any IE-only API inside it will not be reported here. Under a Content-Security-Policy without unsafe-eval (a common Chrome hardening step) these calls also fail at runtime.',
          recommendation:
            'Refactor to a function reference. If the string is assembled from server data, move the data into JSON and keep the logic static. Manual work only; automatic rewriting would change semantics.',
          evidence: {
            kind: 'DynamicCode',
            matched: ctx.text.slice(node.start ?? 0, node.end ?? 0).slice(0, 200),
            container: unit.container,
            detail: { api },
          },
        }),
      );
    });
    return out;
  },
});

export const dynamicRules: RuleDraft[] = ruleList;
export { asRule, intersectsRegions };
